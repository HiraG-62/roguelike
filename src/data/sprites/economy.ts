/** 商人の衣（橙の 5 段）を差し替えて色違いを作る。描画側の再配色と同じく文字の置き換えだけ */
function robe(frames: SpriteFrames, ramp: string): SpriteFrames {
  const from = ["q", "(", "o", ")", "O"];
  return frames.map((frame) => frame.map((row) => [...row].map((ch) => { const i = from.indexOf(ch); return i < 0 ? ch : (ramp[i] ?? ch); }).join("")));
}

