function merchantFamily(): Record<string, SpriteFrames> {
  const out: Record<string, SpriteFrames> = {
    merchant: MERCHANT_WALK,
    [poseKey("merchant", "windup")]: [MERCHANT_WINDUP],
    [poseKey("merchant", "strike")]: [MERCHANT_STRIKE],
  };
  for (const [key, ramp] of Object.entries(MERCHANT_ROBES)) {
    out[key] = robe(MERCHANT_WALK, ramp);
    out[poseKey(key, "windup")] = robe([MERCHANT_WINDUP], ramp);
    out[poseKey(key, "strike")] = robe([MERCHANT_STRIKE], ramp);
  }
  return out;
}

